#!/usr/bin/env python3
"""Generate a .env with strong random secrets for local Compose, or print the secret map as JSON for the cloud.

    python3 scripts/gen-env.py                 # writes .env (refuses to overwrite)
    python3 scripts/gen-env.py --json          # prints secrets JSON (used by deploy scripts)

Terraform generates the same keys for AWS Secrets Manager / Google Secret Manager; see infra/*/secrets.tf.
"""
from __future__ import annotations

import argparse
import json
import secrets
import string
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def token(n: int = 32) -> str:
    return secrets.token_urlsafe(n)[:n]


def password(n: int = 24) -> str:
    # Flowise requires upper, lower, digit and special characters.
    alphabet = string.ascii_letters + string.digits
    core = "".join(secrets.choice(alphabet) for _ in range(n - 4))
    return f"Aa1!{core}"


def secret_map() -> dict[str, str]:
    return {
        "POSTGRES_PASSWORD": token(28),
        "PLANNER_API_KEY": "pl-" + token(32),
        "MANAGER_API_KEY": "mg-" + token(32),
        "FLOWISE_TOOL_KEY": "fw-" + token(32),
        "LANGGRAPH_TOOL_KEY": "lg-" + token(32),
        "MCP_TOOL_KEY": "mt-" + token(32),
        "MCP_CLIENT_KEY": "mc-" + token(32),
        "QWEN_API_KEY": "qw-" + token(32),
        "FLOWISE_ADMIN_PASSWORD": password(),
        "FLOWISE_SECRETKEY": token(32),
        "FLOWISE_JWT_SECRET": token(40),
        "FLOWISE_JWT_REFRESH_SECRET": token(40),
        "FLOWISE_SESSION_SECRET": token(40),
        "FLOWISE_TOKEN_HASH_SECRET": token(40),
        "GRAFANA_ADMIN_PASSWORD": password(),
        "LANGFUSE_PUBLIC_KEY": "pk-lf-" + secrets.token_hex(16),
        "LANGFUSE_SECRET_KEY": "sk-lf-" + secrets.token_hex(16),
        "LANGFUSE_NEXTAUTH_SECRET": token(40),
        "LANGFUSE_SALT": token(32),
        "LANGFUSE_ENCRYPTION_KEY": secrets.token_hex(32),
        "LANGFUSE_ADMIN_PASSWORD": password(),
        "CLICKHOUSE_PASSWORD": token(24),
        "REDIS_PASSWORD": token(24),
        "MINIO_PASSWORD": token(24),
        # SupplyChain Insight AI service users (hashed in its database; the Flowise flows get only the agent key)
        **{f"SCI_{slot}_KEY": f"sci-{slot.lower()}-" + token(32) for slot in ("AGENT", "PLANNER", "PROCUREMENT", "WAREHOUSE", "LOGISTICS",
                                                                             "QUALITY", "DIRECTOR", "SAP_EXECUTOR", "MLOPS", "OTHER_TENANT")},
    }


LOCAL_SETTINGS = {
    "APP_ENV": "development",
    "CLOUD_PROVIDER": "local",
    "POSTGRES_HOST": "postgres",
    "POSTGRES_USER": "supplychain",
    "QWEN_BASE_URL": "http://host.docker.internal:11435/v1",
    "QWEN_MODEL": "qwen2.5-7b-scm",
    "LLM_MODE": "qwen",
    # Simple local-demo logins (cloud deployments get random ones from Terraform). Grafana is admin/admin; Flowise and
    # Langfuse require an e-mail login and a strong 8+ character password, so they share admin@admin.com / Admin@admin1.
    "FLOWISE_ADMIN_EMAIL": "admin@admin.com",
    "FLOWISE_ADMIN_PASSWORD": "Admin@admin1",
    "GRAFANA_ADMIN_PASSWORD": "admin",
    "LANGFUSE_ADMIN_EMAIL": "admin@admin.com",
    "LANGFUSE_ADMIN_PASSWORD": "Admin@admin1",
    "LANGFUSE_INTERNAL_URL": "http://langfuse:3000",
    "GRAFANA_INTERNAL_URL": "http://grafana:3000",
    "PUBLIC_BASE_URL": "http://localhost:8000",
    "PUBLIC_FLOWISE_URL": "http://localhost:3000",
    "PUBLIC_LANGGRAPH_URL": "http://localhost:8123",
    "PUBLIC_MCP_URL": "http://localhost:8002",
    "PUBLIC_GRAFANA_URL": "http://localhost:3002",
    "PUBLIC_LANGFUSE_URL": "http://localhost:3003",
    "FLOWISE_API_KEY": "",
}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--add-missing", action="store_true", help="append newly introduced keys to an existing .env, keep all current values")
    args = parser.parse_args()
    values = secret_map()
    if args.add_missing:
        target = ROOT / ".env"
        current = {line.split("=", 1)[0] for line in target.read_text().splitlines() if "=" in line} if target.exists() else set()
        new = {k: v for k, v in {**values, **LOCAL_SETTINGS}.items() if k not in current}
        if target.exists() and new:
            with target.open("a") as handle:
                handle.write("".join(f"{k}={v}\n" for k, v in new.items()))
        print(f"added {len(new)} new setting(s) to {target}" if new else "no new settings")
        return 0
    if args.json:
        print(json.dumps(values))
        return 0
    target = ROOT / ".env"
    if target.exists() and not args.force:
        print(f"{target} exists; use --force to replace it", file=sys.stderr)
        return 1
    lines = ["# Generated by scripts/gen-env.py — local development secrets. Never commit."]
    lines += [f"{k}={v}" for k, v in {**values, **LOCAL_SETTINGS}.items()]
    target.write_text("\n".join(lines) + "\n")
    target.chmod(0o600)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
